import type { AlertsResponse } from "../../api/types";
import "./AlertSummary.css";

interface AlertSummaryProps {
  alerts: AlertsResponse | null;
  isLoading: boolean;
  error: string | null;
  onRetry: () => void;
}

const ALERT_THRESHOLD = 0.045;

const formatScore = (score: number) => (score * 100).toFixed(1);

export function AlertSummary({ alerts, isLoading, error, onRetry }: AlertSummaryProps) {
  if (isLoading) {
    return (
      <div className="alert-summary">
        <h2>Alert Summary</h2>
        <div className="alert-loading">Loading alert data…</div>
      </div>
    );
  }

  if (error) {
    return (
      <div className="alert-summary">
        <h2>Alert Summary</h2>
        <div className="alert-error">
          <p>{error}</p>
          <button type="button" className="btn btn-secondary" onClick={onRetry}>
            Retry
          </button>
        </div>
      </div>
    );
  }

  if (!alerts || !alerts.alert_summary) {
    return (
      <div className="alert-summary">
        <h2>Alert Summary</h2>
        <div className="alert-empty">
          <p>No alert events recorded for this patient.</p>
          <p className="alert-empty-hint">
            This does not indicate the patient is safe. Alert events are generated by
            the model when the filtered risk score exceeds the threshold.
          </p>
        </div>
      </div>
    );
  }

  const { alert_summary } = alerts;
  const hasAlerts = alert_summary.total_alerts > 0;
  const duration =
    alert_summary.last_alert_iculos - alert_summary.first_alert_iculos + 1;
  const isHighPeak = alert_summary.max_peak_risk >= ALERT_THRESHOLD;

  return (
    <div className="alert-summary">
      <h2>Alert Summary</h2>

      {hasAlerts ? (
        <>
          <div className="alert-stats-grid">
            <div className="alert-stat-item">
              <span className="alert-stat-label">Total Alert Events</span>
              <span className={`alert-stat-value ${hasAlerts ? "alert-active" : ""}`}>
                {alert_summary.total_alerts}
              </span>
            </div>
            <div className="alert-stat-item">
              <span className="alert-stat-label">Alert Hours</span>
              <span className="alert-stat-value">
                {alert_summary.total_alert_hours}
              </span>
            </div>
            <div className="alert-stat-item">
              <span className="alert-stat-label">First Alert</span>
              <span className="alert-stat-value">
                ICULOS {alert_summary.first_alert_iculos}
              </span>
            </div>
            <div className="alert-stat-item">
              <span className="alert-stat-label">Last Alert</span>
              <span className="alert-stat-value">
                ICULOS {alert_summary.last_alert_iculos}
              </span>
            </div>
            <div className="alert-stat-item">
              <span className="alert-stat-label">Alert Duration</span>
              <span className="alert-stat-value">
                {duration} {duration === 1 ? "hour" : "hours"}
              </span>
            </div>
            <div className="alert-stat-item">
              <span className="alert-stat-label">Max Peak Risk</span>
              <span className={`alert-stat-value ${isHighPeak ? "risk-high" : "risk-low"}`}>
                {formatScore(alert_summary.max_peak_risk)}%
              </span>
            </div>
          </div>

          <div className="alert-threshold-note">
            <strong>Alert threshold:</strong> {formatScore(ALERT_THRESHOLD)}% filtered risk over 2
            consecutive ICU hours. Alert events are model-generated, not clinical diagnoses.
          </div>
        </>
      ) : (
        <div className="alert-empty">
          <p>No alert events recorded for this patient.</p>
          <p className="alert-empty-hint">
            This does not indicate the patient is safe. Alert events are generated by
            the model when the filtered risk score exceeds the threshold.
          </p>
        </div>
      )}
    </div>
  );
}
