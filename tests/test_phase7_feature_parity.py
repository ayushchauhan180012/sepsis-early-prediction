"""Phase 7 — committed feature-parity fixture tests (O-8 resolution, D-023).

``tests/fixtures/feature_parity.csv`` stores RAW observation inputs (PatientID,
ICULOS, Age, vitals, labs) alongside the EXPECTED 50-feature output (columns
``expected_*``) for real patients drawn from the training dataset.  The
fixture is generated by ``tests/generate_fixtures.py`` which cross-checks the
production transform against a verbatim reproduction of the notebook's cells 6
and 8.

These tests pin the production transform to that committed record, so ANY
change to ``Services/feature_engineering.py`` that drifts from the frozen
training semantics is caught in CI — without needing the training dataset or
PostgreSQL at test time.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from Backend.Services.feature_engineering import transform_patient_history
from Backend.config import FEATURE_NAMES, LABS, VITALS

FIXTURES = Path(__file__).resolve().parent / "fixtures"
FEATURE_PARITY_CSV = FIXTURES / "feature_parity.csv"

RAW_COLS = ["PatientID", "ICULOS", "Age"] + VITALS + LABS
EXPECTED_COLS = [f"expected_{c}" for c in FEATURE_NAMES]


@pytest.fixture(scope="module")
def parity_fixture() -> pd.DataFrame:
    if not FEATURE_PARITY_CSV.exists():
        pytest.fail(
            f"missing fixture {FEATURE_PARITY_CSV} — regenerate it with "
            "tests/generate_fixtures.py --dataset <training_csv>"
        )
    return pd.read_csv(FEATURE_PARITY_CSV)


def _histories(fixture: pd.DataFrame):
    """Yield (patient_id, raw_history_df, expected_features_df) per patient."""
    for patient_id, grp in fixture.groupby("PatientID", sort=False):
        grp = grp.sort_values("ICULOS").reset_index(drop=True)
        raw = grp[RAW_COLS].copy()
        expected = grp[EXPECTED_COLS].rename(
            columns={c: c.removeprefix("expected_") for c in EXPECTED_COLS}
        )
        yield str(patient_id), raw, expected


def test_fixture_schema_is_frozen_contract(parity_fixture):
    """The fixture must contain exactly the raw inputs plus all 50 features."""
    assert list(parity_fixture.columns) == RAW_COLS + EXPECTED_COLS
    assert parity_fixture["PatientID"].nunique() >= 3
    assert len(parity_fixture) >= 40
    assert (parity_fixture["ICULOS"] >= 1).all()
    assert (parity_fixture["Age"] >= 0).all()


def test_production_transform_reproduces_every_fixture_row(parity_fixture):
    """transform_patient_history must reproduce the committed expected rows."""
    checks = 0
    for patient_id, raw, expected in _histories(parity_fixture):
        produced = transform_patient_history(raw)
        assert list(produced.columns) == list(FEATURE_NAMES), patient_id
        assert len(produced) == len(expected), patient_id
        assert (
            produced["ICULOS"].to_numpy() == expected["ICULOS"].to_numpy()
        ).all(), patient_id
        ok = np.isclose(
            produced.to_numpy(dtype=float),
            expected.to_numpy(dtype=float),
            rtol=1e-6,
            atol=1e-5,
            equal_nan=True,
        )
        bad = np.argwhere(~ok)
        if len(bad):
            row, col = bad[0]
            feat = produced.columns[col]
            pytest.fail(
                f"{patient_id} ICULOS {produced.iloc[row]['ICULOS']}: "
                f"feature {feat} production={produced.iloc[row, col]!r} "
                f"fixture={expected.iloc[row, col]!r}"
            )
        checks += 1
    assert checks == parity_fixture["PatientID"].nunique()


def test_non_lab_expected_features_are_finite(parity_fixture):
    """All non-raw-lab features are fully defined (no stray NaN)."""
    finite_cols = [f"expected_{c}" for c in FEATURE_NAMES if c not in LABS]
    assert parity_fixture[finite_cols].notna().all().all()
    # Raw labs may legitimately be NaN (labs are never imputed, D-010).
    assert parity_fixture[LABS].isna().any().any()


def test_expected_feature_order_matches_model_contract(parity_fixture):
    """Column order in the fixture == FEATURE_NAMES == model.feature_names_in_."""
    assert list(parity_fixture.columns) == RAW_COLS + EXPECTED_COLS
    unrounded_features = [c[9:] for c in EXPECTED_COLS]
    assert unrounded_features == list(FEATURE_NAMES)